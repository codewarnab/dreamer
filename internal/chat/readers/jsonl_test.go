func TestReadJSONLWithOptionsSanitizesNoisyClaudePayloadAndKeepsSignal(t *testing.T) {
	filePath := filepath.Join(t.TempDir(), "claude-noisy-session.jsonl")
	contents := strings.Join([]string{
		`{"type":"user","message":{"role":"user","content":"<meta>trace metadata</meta>"},"timestamp":"2026-05-08T12:00:00Z"}`,
		`{"type":"assistant","message":{"role":"assistant","content":"tool_result: {\"ok\":true}"},"timestamp":"2026-05-08T12:00:01Z"}`,
		`{"type":"user","message":{"role":"user","content":"Async agent launched successfully. agentId: a1 output_file: C:\\temp\\a"},"timestamp":"2026-05-08T12:00:02Z"}`,
		`{"type":"user","message":{"role":"user","content":"  Please investigate flaky daemon cycle behavior.  "},"timestamp":"2026-05-08T12:00:03Z"}`,
		`{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"I will inspect runtime and discovery isolation tests."}]},"timestamp":"2026-05-08T12:00:04Z"}`,
		`{"type":"user","message":{"role":"user","content":"Need help\nwith project A/B isolation"},"timestamp":"2026-05-08T12:00:05Z"}`,
	}, "\n")

	if err := os.WriteFile(filePath, []byte(contents), 0o644); err != nil {
		t.Fatalf("WriteFile returned error: %v", err)
	}

	messages, err := ReadJSONLWithOptions(filePath, JSONLReadOptions{SanitizeClaude: true})
	if err != nil {
		t.Fatalf("ReadJSONLWithOptions returned error: %v", err)
	}
	if len(messages) != 3 {
		t.Fatalf("expected 3 sanitized Claude signal messages, got %d", len(messages))
	}

	if got := messages[0].Content; got != "Please investigate flaky daemon cycle behavior." {
		t.Fatalf("first message content = %q, want kept user signal", got)
	}
	if got := messages[1].Content; got != "I will inspect runtime and discovery isolation tests." {
		t.Fatalf("second message content = %q, want kept assistant signal", got)
	}
	if got := messages[2].Content; got != "Need help with project A/B isolation" {
		t.Fatalf("third message content = %q, want normalized user signal", got)
	}

	joined := strings.ToLower(messages[0].Content + " " + messages[1].Content + " " + messages[2].Content)
	for _, unwanted := range []string{"<meta>", "tool_result", "async agent launched successfully", "output_file:"} {
		if strings.Contains(joined, unwanted) {
			t.Fatalf("sanitized messages should not include %q: %q", unwanted, joined)
		}
	}
}

